"""Quivers Indexed Effect Core (QIEC) reference kernel.

QIEC is a small typed value/computation IR for indexed families and algebraic
effects.  It is deliberately independent of the QVR surface grammar and the
target probabilistic IR: the compiler may lower into QIEC incrementally, while
Didactic and Panproto check its first-order indexed-family projection.
"""

